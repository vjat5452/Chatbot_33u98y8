from fpdf import FPDF


class ChunkStructurePDF(FPDF):
    def header(self):
        self.set_font('Helvetica', 'B', 14)
        self.cell(0, 10, 'Sparrow Interactive - Chunk Storage & Retrieval Architecture', 0, new_x='LMARGIN', new_y='NEXT', align='C')
        self.set_font('Helvetica', '', 9)
        self.cell(0, 6, 'Generated: 2026-03-25 | Collection: sql_chunks | Qdrant: localhost:6333', 0, new_x='LMARGIN', new_y='NEXT', align='C')
        self.ln(2)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()}/{{nb}}', 0, align='C')

    def section_title(self, title):
        self.set_font('Helvetica', 'B', 13)
        self.set_fill_color(41, 128, 185)
        self.set_text_color(255, 255, 255)
        self.cell(0, 9, f'  {title}', 0, new_x='LMARGIN', new_y='NEXT', fill=True)
        self.set_text_color(0, 0, 0)
        self.ln(4)

    def sub_title(self, title):
        self.set_font('Helvetica', 'B', 11)
        self.set_fill_color(230, 240, 250)
        self.cell(0, 7, f'  {title}', 0, new_x='LMARGIN', new_y='NEXT', fill=True)
        self.ln(3)

    def body(self, text):
        self.set_font('Helvetica', '', 9)
        self.multi_cell(0, 4.5, text)
        self.ln(2)

    def body_bold(self, text):
        self.set_font('Helvetica', 'B', 9)
        self.multi_cell(0, 4.5, text)
        self.ln(1)

    def bullet(self, text):
        self.set_font('Helvetica', '', 9)
        self.cell(8, 4.5, '-')
        self.multi_cell(0, 4.5, text)
        self.ln(1)

    def code_block(self, text):
        self.set_font('Courier', '', 8)
        self.set_fill_color(245, 245, 245)
        self.multi_cell(0, 4, text, fill=True)
        self.ln(2)

    def separator(self):
        y = self.get_y()
        self.set_draw_color(200, 200, 200)
        self.line(15, y, 195, y)
        self.ln(4)


